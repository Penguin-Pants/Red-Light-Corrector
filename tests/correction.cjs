'use strict';
const assert = require('node:assert/strict');
require('../src/correction.js');
const { analyze, apply, modes } = globalThis.RlcCorrection;
let pixels = new Uint8ClampedArray([128,128,128,255,30,30,30,255]);
const neutral = analyze(pixels);
assert.deepEqual(Object.keys(neutral), modes);
apply(pixels, neutral.Natural);
assert.deepEqual([...pixels], [128,128,128,255,30,30,30,255]);
pixels = new Uint8ClampedArray([190,90,70,255,140,65,55,255,110,50,41,255]);
const cast = analyze(pixels);
assert.deepEqual(analyze(pixels), cast);
apply(pixels, cast.Balanced);
assert.ok(pixels[0] - pixels[1] < 100);
assert.equal(pixels[3], 255);
const severe = analyze(new Uint8ClampedArray([255,0,0,255,245,1,0,255]));
assert.equal(severe.Natural.confidence, 'Low');
assert.ok(severe.Natural.reasons.length >= 2);
const hidden = analyze(new Uint8ClampedArray([255,0,0,0]));
assert.equal(hidden.Balanced.confidence, 'Low');
